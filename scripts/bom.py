"""
Printed-parts bill of materials with filament mass per part, per material, and in total.
Run from the repo root:  python3 scripts/bom.py  -> data/bom_printed.csv, docs/bom.md

Mass model (an estimate; the slicer's number is the authoritative one):
  shell  = surface area x wall thickness (walls x 0.42 mm line width), capped at the part volume
  mass   = density x (shell + infill fraction x (volume - shell)) x (1 + support allowance)
Specimens print effectively solid (every wall is perimeters), so their mass is density x volume.
Densities: Bambu PLA-CF 1.22, Bambu PAHT-CF 1.06 (Bambu technical data sheets); PLA 1.24 (typical).
"""
import csv
import sys

import cadquery as cq

sys.path.insert(0, "scripts")
import rig  # noqa: E402

DENSITY = {"PLA": 1.24, "PLA-CF": 1.22, "PAHT-CF": 1.06}
LINE_W = 0.42
MATERIALS = ("PLA", "PLA-CF", "PAHT-CF")


def load(path):
    return cq.importers.importStep(path).val()


def est_mass(shape, material, walls, infill, support=0.0, solid=False):
    vol = shape.Volume() / 1000.0                       # cm3
    if solid:
        return vol, vol * DENSITY[material]
    shell = min(vol, shape.Area() * walls * LINE_W / 1000.0)
    return vol, DENSITY[material] * (shell + infill * (vol - shell)) * (1 + support)


# (group, file stem, description, qty, material, walls, infill, support allowance, solid, note)
SPEC = []
for m in MATERIALS:
    SPEC += [
        ("Specimen", "cad/03_triangle_isogrid_25x25", "Triangle isogrid beam", 3, m, 0, 0, 0, True, "test specimen"),
        ("Specimen", "cad/04_hexagon_honeycomb_25x25", "Hexagon honeycomb beam", 3, m, 0, 0, 0, True, "test specimen"),
        ("Specimen", "cad/00_solid_flex_bar_127x12.7x3.2", "Solid flex bar", 3, m, 0, 0, 0, True, "base-material test"),
    ]
RIG = [
    ("Rig", "rig/01_base", "Base", 1, "PLA", 4, 0.25, 0.0, False, "~9 MPa peak; stiffness does not affect the data"),
    ("Rig", "rig/02_support_saddle", "Support saddle", 2, "PAHT-CF", 6, 0.60, 0.0, False, "carries 1 kN each"),
    ("Rig", "rig/03_beam_support_pad", "Beam support pad", 2, "PAHT-CF", 0, 1.0, 0.0, True, "100% infill"),
    ("Rig", "rig/04_bar_support_pad", "Bar support pad (R5)", 2, "PAHT-CF", 0, 1.0, 0.0, True, "100% infill"),
    ("Rig", "rig/05_beam_loading_nose", "Beam loading nose", 1, "PAHT-CF", 0, 1.0, 0.0, True, "100% infill"),
    ("Rig", "rig/06_bar_loading_nose", "Bar loading nose (R5)", 1, "PAHT-CF", 0, 1.0, 0.0, True, "100% infill"),
    ("Rig", "rig/07_lever", "Lever", 1, "PLA-CF", 5, 0.40, 0.0, False, "print on its side; ~10 MPa peak at 2 kN"),
    ("Rig", "rig/08_bearing_spacer", "Bearing spacer", 2, "PAHT-CF", 0, 1.0, 0.0, True, ""),
    ("Rig", "rig/09_plate_peg_standard", "Plate peg, 1-inch plates", 1, "PLA-CF", 4, 0.30, 0.0, False, "print this OR the Olympic peg"),
    ("Rig", "rig/10_plate_peg_olympic", "Plate peg, Olympic plates", 0, "PLA-CF", 4, 0.30, 0.0, False, "qty 1 if your plates have 2-inch holes"),
    ("Rig", "rig/11_weight_tray", "Weight tray (flex bars)", 1, "PLA-CF", 3, 0.15, 0.0, False, "sits on the 1-inch peg"),
    ("Rig", "rig/12_beam_deflection_yoke", "Beam deflection yoke", 1, "PLA-CF", 4, 0.30, 0.15, False, "supports"),
    ("Rig", "rig/13_bar_deflection_yoke", "Bar deflection yoke", 1, "PLA-CF", 4, 0.30, 0.15, False, "supports"),
    ("Rig", "rig/14_indicator_clamp_8mm", "Indicator clamp, 8 mm stem", 1, "PLA-CF", 4, 0.50, 0.0, False, "print this OR the 3/8 in clamp"),
    ("Rig", "rig/15_indicator_clamp_3-8in", "Indicator clamp, 3/8 in stem", 0, "PLA-CF", 4, 0.50, 0.0, False, "qty 1 for a US indicator"),
]


def main():
    rows = []
    for grp, stem, desc, qty, mat, walls, infill, sup, solid, note in SPEC + RIG:
        vol, g = est_mass(load(stem + ".step"), mat, walls, infill, sup, solid)
        settings = "solid (all perimeters)" if solid and grp == "Specimen" else \
            ("100% infill" if solid else f"{walls} walls, {int(infill * 100)}% infill" + (", supports" if sup else ""))
        rows.append(dict(group=grp, part=desc, file=stem, material=mat, qty=qty, settings=settings,
                         volume_cm3=round(vol, 2), mass_each_g=round(g, 1), mass_total_g=round(g * qty, 1), note=note))
    with open("data/bom_printed.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)

    tot = {m: {"Specimen": 0.0, "Rig": 0.0} for m in MATERIALS}
    cnt = {m: {"Specimen": 0, "Rig": 0} for m in MATERIALS}
    for r in rows:
        tot[r["material"]][r["group"]] += r["mass_total_g"]
        cnt[r["material"]][r["group"]] += r["qty"]

    md = ["# Bill of materials", "",
          "Generated by `scripts/bom.py` from the CAD. Masses are estimates from part volume, surface area and the "
          "print settings listed (wall line width 0.42 mm). Check them against the slicer before buying filament.", "",
          "## Filament totals", "",
          "| Material | Specimens (prints) | Specimens (g) | Rig (prints) | Rig (g) | Total (g) | With 10% margin (g) |",
          "|---|---|---|---|---|---|---|"]
    for m in MATERIALS:
        s, r_ = tot[m]["Specimen"], tot[m]["Rig"]
        md.append(f"| {m} | {cnt[m]['Specimen']} | {s:.0f} | {cnt[m]['Rig']} | {r_:.0f} | {s + r_:.0f} | {(s + r_) * 1.1:.0f} |")
    gt = sum(tot[m]["Specimen"] + tot[m]["Rig"] for m in MATERIALS)
    md += [f"| **All** | {sum(cnt[m]['Specimen'] for m in MATERIALS)} | | {sum(cnt[m]['Rig'] for m in MATERIALS)} | | "
           f"**{gt:.0f}** | **{gt * 1.1:.0f}** |", ""]
    for m in MATERIALS:
        md += [f"## {m}", "", "| Part | Qty | Settings | g each | g total | Note |", "|---|---|---|---|---|---|"]
        for r in rows:
            if r["material"] == m and r["qty"] > 0:
                md.append(f"| {r['part']} (`{r['file']}`) | {r['qty']} | {r['settings']} | {r['mass_each_g']} | "
                          f"{r['mass_total_g']} | {r['note']} |")
        md.append("")
    md += ["## Alternates (not counted above)", "", "| Part | Material | g each | Use instead of |", "|---|---|---|---|"]
    for r in rows:
        if r["qty"] == 0:
            md.append(f"| {r['part']} (`{r['file']}`) | {r['material']} | {r['mass_each_g']} | {r['note']} |")
    md += ["", "## Hardware", "",
           "| Item | Qty | Where | Status |", "|---|---|---|---|",
           "| 608-2RS bearing | 2 | Pressed into the lever at the pivot | Already in the workshop |",
           "| M8 x 80 hex bolt, partially threaded (ISO 4014 / DIN 931) | 1 | Lever pivot through the tower cheeks | Probably on hand. Check: plain shank at least 55 mm long, so no thread sits inside a bearing |",
           "| M8 nyloc nut | 1 | Lever pivot | Needed |",
           "| M8 washer | 2 | Under the bolt head and the nut | Needed |",
           "| M5 heat-set insert | 8 | Rail: 2 per saddle position, both spans | Needed |",
           "| M5 x 16 socket-head screw | 4 | 2 per saddle | Needed |",
           "| M3 heat-set insert | 2 | Indicator clamp: ear and post socket | Needed |",
           "| M3 x 12 socket-head screw | 1 | Indicator clamp, stem pinch | Needed |",
           "| M3 x 10 socket-head screw | 1 | Indicator clamp, post lock | Needed |",
           "| Dial indicator, 0.01 mm, 10 mm travel | 1 | On the deflection yoke | Needed unless you have one. Required: nothing printed reads to 0.01 mm. |",
           "| Weights | up to ~38 kg | On the plate peg | Gym plates |",
           "| Water, sand or washers | up to ~5 kg | In the weight tray (flex bars) | Weigh each addition on a kitchen scale |",
           ""]
    open("docs/bom.md", "w").write("\n".join(md))
    for m in MATERIALS:
        print(f"{m:8s} specimens {tot[m]['Specimen']:6.0f} g ({cnt[m]['Specimen']} prints)   rig {tot[m]['Rig']:6.0f} g ({cnt[m]['Rig']} prints)")
    print(f"total {gt:.0f} g")


if __name__ == "__main__":
    main()
